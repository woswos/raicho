from automation.release.raicho_version import write_product_version
from automation.testing.raicho_guard_fixtures import GuardTestCase

CARGO = """[workspace]
members = ["server", "helper"]

[workspace.package]
version = "0.1.0"
"""

LOCKFILE = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "example"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "unchanged"

[[package]]
name = "raicho-helper"
version = "0.1.0"

[[package]]
name = "raicho-helper"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "also-unchanged"

[[package]]
name = "raicho-server"
version = "0.1.0"
dependencies = [
 "example",
 "raicho-helper 0.1.0",
 "raicho-helper 0.1.0 (registry+https://github.com/rust-lang/crates.io-index)",
]
"""

MANIFEST = '{"manifest_version": 2, "version": "0.1.0"}\n'


class VersionLockTests(GuardTestCase):
    def prepare_workspace(self):
        repo = self.repo()
        repo.write('Cargo.toml', CARGO)
        repo.write('Cargo.lock', LOCKFILE)
        for directory in ('server', 'helper'):
            repo.write(
                f'{directory}/Cargo.toml',
                f'[package]\nname = "raicho-{directory}"\nversion.workspace = true\n',
            )
        repo.write('extension/manifest.json', MANIFEST)
        return repo

    def test_bump_preserves_dependencies_and_updates_workspace_references(self):
        repo = self.prepare_workspace()
        write_product_version(repo.root, '0.2.0')
        expected = LOCKFILE.replace(
            'name = "raicho-helper"\nversion = "0.1.0"\n\n',
            'name = "raicho-helper"\nversion = "0.2.0"\n\n',
        ).replace(
            'name = "raicho-server"\nversion = "0.1.0"',
            'name = "raicho-server"\nversion = "0.2.0"',
        )
        expected = expected.replace('"raicho-helper 0.1.0",', '"raicho-helper 0.2.0",')
        self.assertEqual((repo.root / 'Cargo.lock').read_text(), expected)
        self.assertEqual(
            (repo.root / 'Cargo.toml').read_text(), CARGO.replace('0.1.0', '0.2.0')
        )
        self.assertEqual(
            (repo.root / 'extension/manifest.json').read_text(),
            MANIFEST.replace('0.1.0', '0.2.0'),
        )

    def test_invalid_lockfile_leaves_every_version_file_unchanged(self):
        invalid_locks = (
            'version = [\n',
            LOCKFILE.replace('name = "raicho-server"', 'name = "missing-server"'),
            LOCKFILE.replace(
                'name = "raicho-server"\nversion = "0.1.0"',
                'name = "raicho-server"\nversion = "9.9.9"',
            ),
            LOCKFILE + '\n[[package]]\nname = "raicho-server"\nversion = "0.1.0"\n',
        )
        for lockfile in invalid_locks:
            with self.subTest(lockfile=lockfile):
                repo = self.prepare_workspace()
                repo.write('Cargo.lock', lockfile)
                with self.assertRaises(ValueError):
                    write_product_version(repo.root, '0.2.0')
                self.assertEqual((repo.root / 'Cargo.toml').read_text(), CARGO)
                self.assertEqual((repo.root / 'Cargo.lock').read_text(), lockfile)
                self.assertEqual(
                    (repo.root / 'extension/manifest.json').read_text(), MANIFEST
                )

    def test_missing_lockfile_leaves_manifest_unchanged(self):
        repo = self.prepare_workspace()
        (repo.root / 'Cargo.lock').unlink()
        with self.assertRaises(FileNotFoundError):
            write_product_version(repo.root, '0.2.0')
        self.assertEqual((repo.root / 'Cargo.toml').read_text(), CARGO)
        self.assertEqual((repo.root / 'extension/manifest.json').read_text(), MANIFEST)

    def test_invalid_extension_manifest_leaves_cargo_files_unchanged(self):
        repo = self.prepare_workspace()
        repo.write('extension/manifest.json', '{"manifest_version": 2}\n')
        with self.assertRaises(ValueError):
            write_product_version(repo.root, '0.2.0')
        self.assertEqual((repo.root / 'Cargo.toml').read_text(), CARGO)
        self.assertEqual((repo.root / 'Cargo.lock').read_text(), LOCKFILE)
